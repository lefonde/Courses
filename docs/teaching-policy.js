/* Shared tutor instructions and notebook references. No progress or storage access. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.StudyTeachingPolicy = api;
})(typeof window === 'undefined' ? globalThis : window, function () {
  'use strict';
  const modes = [
    {id: 'guided', label: 'פתרון בהכוונה', description: 'אני מנסה ומקבל הכוונה כשצריך, בלי לעצור אחרי כל צעד.'},
    {id: 'independent', label: 'ניסיון עצמאי ואז פתרון מלא', description: 'אני מנסה את השאלה במלואה; כשאבקש, אקבל פתרון מוסבר, טעויות נפוצות ותבנית כללית.'}
  ];
  const normalizeMode = value => value === 'independent' ? value : 'guided';
  function notebookContext() {
    return 'מקורות: חומרי הקורס כבר נמצאים במחברת NotebookLM המחוברת לשיחה הזאת. השתמש במקורות המחברת; שמות המסמכים להלן הם פרטי זיהוי, ולא נתיבים במחשב או בקשה לחיפוש ב־Drive. אין צורך לבקש חיבור או הרשאות ל־Google Drive או ל־Google Workspace, או העלאה חוזרת של מקור שכבר זמין במחברת. חפש לפי שם המסמך, מספר המטלה או השיעור, מספר השאלה והתוכן. ייתכנו הבדלים קטנים בשם, כגון סיומת מספרית; אמת את זהות השאלה לפי התוכן. רק אם מקור לא נמצא לאחר בדיקה במחברת, ציין בדיוק מה חסר ובקש שאבחר או אוסיף אותו למחברת. אם אין לך בפועל גישה למחברת, אמור זאת ובקש שאצרף אותה לשיחה או אדביק את הקטע הדרוש. אל תציג זאת כצורך בהרשאת Drive, ואל תמציא תוכן שלא קראת.';
  }
  const list = value => Array.isArray(value) ? value : value == null ? [] : [value];
  function sourceText(source, ref = {}) {
    if (!source) return 'מקור שלא זוהה; יש לברר את המסמך המתאים במחברת.';
    const name = String(source.path || '').split(/[\\/]/).pop();
    const parts = [source.label || name || 'מקור במחברת'];
    if (name && name !== parts[0]) parts.push(`מסמך לזיהוי: ${name}`);
    const pages = list(ref.pages);
    const pdf = pages.map(page => typeof page === 'object' && page !== null ? page.pdf ?? page.from ?? page.page : page).filter(page => page != null);
    const printed = pages.filter(page => typeof page === 'object' && page !== null).map(page => page.printed).filter(page => page != null);
    if (pdf.length) parts.push(`עמודי PDF: ${pdf.join(', ')}`);
    if (printed.length) parts.push(`עמודים מודפסים: ${printed.join(', ')}`);
    if (ref.label) parts.push(ref.label);
    if (ref.section) parts.push(`סעיף: ${ref.section}`);
    return parts.join(' | ');
  }
  function supportsMode(session) {
    return !!session && session.stage !== 'foundation' && !['setup', 'mock'].includes(session.kind) && !['mock1-prepare', 'coverage-audit', 'mock1-review', 'mock2-review'].includes(session.id);
  }
  function activityForSession(session) {
    if (session.stage === 'foundation') return 'foundation';
    return session.kind === 'review' ? 'recall' : 'practice';
  }
  function policy(mode, activity = 'practice') {
    const common = [
      'כל ההוראה בעברית ברורה. שמור על הנוסח המחייב והגבלות השאלה במקור. הסבר סימון לא מוכר, אך תן לי להציע משתנים חדשים הדרושים לפתרון. נוסחאות בשורה נפרדת ומשמאל לימין; אם נוצר עמוד, מצב כהה כברירת מחדל.',
      'בדוק את הטענות המילוליות לצד הנוסחאות, לרבות תנאי משפטים וקצב דעיכה. הבחֵן בין תוצאה נכונה, נימוק חסר וטענה שגויה; אל תאשר תשובה שלמה כשחלקה שגוי. תיקון קצר שאינו מגלה את המשך הפתרון אינו מחייב סבב שאלות. אל תשכתב חישוב נכון שכבר הצגתי ואל תניח שטעות נובעת רק מחשיבה: ייתכנו חוסר ידע, שכחה, סימון לא ברור או טעות חישוב. קבל דרך חלופית תקפה.',
      'בסיום תן תיעוד קצר: אילו החלטות ונימוקים היו שלי, מה הצלחתי אחרי רמז, מה סיפקת או הדגמת, ואיך התמודדתי עם החישובים. ציין מה נבדק בפועל ומה נותר. עזרה בבחירת הדרך היא עזרה גם אם ביצעתי את כל החישובים בעצמי. קריאת פתרון אינה פתרון עצמאי. אל תסיק ציון צפוי. שחזור ווריאציה הם אפשרות לפי בקשתי, ולא תנאי לסיום. התקציב המתוכנן אינו מדידה של הזמן שנותר; אל תנחש כמה זמן עבר.'
    ];
    if (['foundation', 'demonstration', 'wrapup'].includes(activity)) {
      const purpose = {
        foundation: 'זהו שלב לבניית ידע. ברר בקצרה מה מוכר לי ולמד ישירות מושג או משפט שחסר; אל תהפוך חוסר ידע למשחק ניחושים. אפשר דוגמה קטנה ואז ניסיון משמעותי שלי. אל תפתור מראש תרגיל עצמאי שיגיע בהמשך.',
        demonstration: 'בחרתי בשלב של דוגמה מוסברת. הסבר אותה בחלקים משמעותיים, עם הסיבות לבחירות ולמעברים. אין צורך לעצור אחרי כל פעולה או לחייב שאלת הבנה על כל מעבר. אפשר לי לשאול ולהמשיך בקצב מתאים. אין להציג זאת כפתרון עצמאי שלי או לפתור תרגיל אחר מראש.',
        wrapup: 'זהו סיכום של העבודה שכבר נעשתה. סכם את ההיגיון והפערים לפי התיעוד והצע נקודת המשך. אל תתחיל תרגיל חדש ואל תחייב שחזור נוסף.'
      }[activity];
      return [purpose, ...common].join('\n\n');
    }
    const selected = normalizeMode(mode);
    const behavior = selected === 'independent' ? [
      'אופן העבודה שבחרתי: ניסיון עצמאי ואז פתרון מלא.',
      'בתחילה הצג את נוסח השאלה המלא ואפשר לי לנסות לפתור אותה במלואה. אל תציג מראש דרך, רמזים, נוסחאות שנבחרו עבורי או תבנית פתרון. המתן שאשלח ניסיון או אבקש עזרה; אם כבר צירפתי ניסיון, התחל בבדיקתו.',
      'אם אשלח ניסיון, בדוק אותו וציין בקצרה מה נכון ומה חסר. אם אבקש רק רמז, תן רק רמז. אם אומר שלא הצלחתי או אבקש פתרון מלא, תן באותה הודעה פתרון שלם ומוסבר, בלי לחייב שאלות מנחות או ניסיון נוסף.',
      'בפתרון מלא, התייחס תחילה לניסיון שלי אם קיים, ואז הצג את הרעיון, בחירת הכלים, תנאי השימוש, המעברים והחישובים עד למסקנה. הוסף שתיים עד ארבע טעויות נפוצות הרלוונטיות לשאלה וכיצד למנוע אותן. לאחר הפתרון בלבד, תן תבנית כללית: מתי היא מתאימה, ההנחות הנדרשות, מה צריך לבחור או לחשב מחדש ומתי אינה תקפה. אל תציג פרטים או קבועים של שאלה אחת כחלק הכרחי מהתבנית.'
    ] : [
      'אופן העבודה שבחרתי: פתרון בהכוונה.',
      'התחל בנוסח השאלה ובהזמנה לניסיון משמעותי שלי, שיכול לכלול כמה צעדים או הוכחה מלאה. אם כבר צירפתי ניסיון, התחל ממנו. אל תפרק את העבודה לסבבי אישור על כל צעד. תן לי לבחור ולהצדיק את הדרך לפני שאתה מציע משתנה, פירוק, משפט או מעבר בהוכחה. אל תפתח במפת פתרון או בשאלה שכבר מכילה את הצעד הרצוי.',
      'לאחר ניסיון שלי, אשר בקצרה מה נכון והתמקד בפער החשוב ביותר. כשנדרשת שאלה מנחה, שאל שאלה ממוקדת אחת והמתן; אין חובה לשאול שאלה בכל הודעה. אפשר לי להתקדם כמה צעדים ברצף. אל תחשב עבורי את הצעד הבא רק מפני שבחרתי את הכלי.',
      'אם אני תקוע, ברר מה הבנתי ותן שאלה ממוקדת או רמז קטן, ואז הזדמנות לניסיון נוסף. אם חסר לי מושג או משפט, הסבר אותו בקצרה והחזר אליי את היישום. אל תכריח אותי לנחש שוב ושוב. אם הטעות חישובית, עזור בחישוב בלי לקחת ממני את יתר ההוכחה. אם אבקש פתרון מלא, תן אותו בלי לכפות עוד ניסיונות.'
    ];
    if (activity === 'recall' || activity === 'mixed') behavior.push('שמור על היקף התרגול שנבחר. בזמן הניסיון אל תתערב ברמזים שלא ביקשתי. ניסיון שהוגש אינו אישור לחשיפת כל ההמשך; פעל לפי בקשת העזרה שלי ולפי אופן העבודה שנבחר.');
    behavior.push('אפשר לשנות את סוג העזרה במהלך השיחה באמצעות ״רמז״, ״הסבר נקודתי״, ״פתרון מלא״ או ״אמשיך לבד״.');
    return [...behavior, ...common].join('\n\n');
  }
  return {modes, normalizeMode, notebookContext, sourceText, supportsMode, activityForSession, policy};
});
